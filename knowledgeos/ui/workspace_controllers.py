def run_research(svc: "KnowledgeService", task: str, doc_id: Optional[str], doc_ids: Optional[list[str]],
                 topic: str, length: str, count: int) -> tuple[str, str, str, Optional[dict[str, Any]]]:
    """Returns (result markdown, citations HTML, notices HTML, exportable payload or None)."""
    topic = (topic or "").strip()
    doc_ids = [d for d in (doc_ids or []) if d]
    if task not in TASKS:
        return "", "", notice("warn", "Choose a task."), None
    if task in NEEDS_DOC and not doc_id:
        return "", "", notice("warn", "Choose a document for this task."), None
    if task in NEEDS_TOPIC and not topic:
        return "", "", notice("warn", "Type a topic, concept or question for this task."), None
    if task == "compare_documents" and len(doc_ids) < 2:
        return "", "", notice("warn", "Select at least two documents to compare."), None
    R = svc.research
    length = length if length in ("short", "medium", "long") else "medium"
    count = int(count or 8)
    try:
        res = {
            "summarize_document": lambda: R.summarize_document(doc_id, length),
            "summarize_section": lambda: R.summarize_section(doc_id, topic, length),
            "compare_documents": lambda: R.compare_documents(doc_ids, topic),
            "explain_concept": lambda: R.explain_concept(topic, doc_ids or None),
            "study_notes": lambda: R.study_notes(doc_id, length),
            "flashcards": lambda: R.flashcards(doc_id, count),
            "quiz": lambda: R.quiz(doc_id, count),
            "report": lambda: R.report(topic, doc_ids or None, length),
            "pros_cons": lambda: R.pros_cons(topic, doc_ids or None),
            "key_terms": lambda: R.key_terms(doc_id),
            "extract_evidence": lambda: R.extract_evidence(topic, doc_ids or None),
        }[task]()
    except KnowledgeOSError as e:
        return "", "", notice("err", safe_user_message(e)), None
    except Exception as e:
        log.exception("research task failed")
        return "", "", notice("err", safe_user_message(e)), None
    msgs = [("warn", w) for w in res.warnings]
    if not msgs:
        msgs = [("ok", "Done." + (" Generated by the LLM from cited passages." if res.used_llm else ""))]
    payload = {"task": res.task, "title": res.title, "markdown": res.markdown, "structured": res.structured,
               "citations": [asdict(c) for c in res.citations], "used_llm": res.used_llm,
               "generated_at": time.strftime("%Y-%m-%d %H:%M:%S")}
    cits = citations_html(res.citations) if res.citations else ""
    return res.markdown, cits, notices(msgs), payload


def export_research(svc: "KnowledgeService", payload: Optional[dict[str, Any]], fmt: str) -> tuple[Optional[str], str]:
    if not payload:
        return None, notice("warn", "Run a task first.")
    try:
        if fmt == "json":
            p = svc.export_text(payload["task"], json.dumps(payload, indent=2, default=str), "json")
        else:
            p = svc.export_text(payload["task"], payload["markdown"], "md")
    except KnowledgeOSError as e:
        return None, notice("err", safe_user_message(e))
    return str(p), notice("ok", f"Exported {p.name}.")


# ============================ evaluation ============================
def _cases(state: Optional[list[dict]]) -> list[EvalCase]:
    return [EvalCase(**d) for d in (state or [])]


def cases_table(state: Optional[list[dict]]) -> pd.DataFrame:
    rows = []
    for c in _cases(state):
        labels = c.relevant_chunk_ids or c.relevant_doc_ids or c.relevant_keywords
        rows.append({"Question": c.question, "Expected answer": c.expected_answer[:80],
                     "Label type": label_type(c), "Relevance labels": "; ".join(labels)[:120]})
    return pd.DataFrame(rows, columns=["Question", "Expected answer", "Label type", "Relevance labels"])


def add_case(state: Optional[list[dict]], question: str, expected: str, keywords: str,
             doc_ids: Optional[list[str]]) -> tuple[list[dict], str]:
    try:
        case = make_case(question, expected, doc_ids or [], [],
                         [k for k in (keywords or "").replace(",", ";").split(";")])
    except KnowledgeOSError as e:
        return list(state or []), notice("warn", safe_user_message(e))
    new = list(state or []) + [asdict(case)]
    note = "" if label_type(case) != "none" else " It has no relevance labels, so retrieval metrics will be blank for it."
    return new, notice("ok", f"Added question #{len(new)}.{note}")


def load_cases_file(state: Optional[list[dict]], path: Optional[str]) -> tuple[list[dict], str]:
    if not path:
        return list(state or []), notice("warn", "Choose a .csv or .json file.")
    p = Path(path)
    if p.suffix.lower() not in (".csv", ".json"):
        return list(state or []), notice("warn", "Only .csv or .json evaluation files are supported.")
    if p.stat().st_size > 2 * 1024 * 1024:
        return list(state or []), notice("warn", "Evaluation files are limited to 2 MB.")
    try:
        text = p.read_text(encoding="utf-8-sig")
        cases = cases_from_json(text) if p.suffix.lower() == ".json" else cases_from_csv(text)
    except KnowledgeOSError as e:
        return list(state or []), notice("err", safe_user_message(e))
    except (UnicodeDecodeError, ValueError) as e:
        return list(state or []), notice("err", f"Could not read the file ({type(e).__name__}).")
    new = list(state or []) + [asdict(c) for c in cases]
    return new, notice("ok", f"Loaded {len(cases)} question(s); {len(new)} in total.")


def load_samples(state: Optional[list[dict]]) -> tuple[list[dict], str]:
    new = list(state or []) + [asdict(c) for c in sample_cases()]
    return new, notice("info", "Added 5 sample questions. They match the synthetic test documents "
                               "(tests/fixture_factory.py); on your own documents, write your own questions.")


def _df(rows: Any) -> pd.DataFrame:
    """DataFrame that always has at least one column (some Gradio versions reject column-less frames)."""
    df = pd.DataFrame(rows)
    return df if len(df.columns) else pd.DataFrame(columns=["result"])


def run_retrieval(svc: "KnowledgeService", state: Optional[list[dict]], strategies: Optional[list[str]], k: int,
                  runs: Optional[list[dict]], progress: Progress = None
                  ) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, list[dict], Optional[dict], str]:
    """Returns (summary, per-question detail, all-runs comparison, runs state, raw result, notice)."""
    runs = list(runs or [])
    strategies = [s for s in (strategies or []) if s in RETRIEVAL_STRATEGIES]
    empty = _df([])
    if not state:
        return empty, empty, _df(runs), runs, None, notice("warn", "Add evaluation questions first.")
    if not strategies:
        return empty, empty, _df(runs), runs, None, notice("warn", "Select at least one strategy.")
    if svc.store.counts()["chunks"] == 0:
        return empty, empty, _df(runs), runs, None, notice("warn", "No indexed documents to evaluate against.")
    try:
        res = run_retrieval_experiment(svc, _cases(state), strategies, int(k), progress)
    except KnowledgeOSError as e:
        return empty, empty, _df(runs), runs, None, notice("err", safe_user_message(e))
    run_no = (max((r["run"] for r in runs), default=0)) + 1
    stamp = time.strftime("%H:%M:%S")
    for row in res["summary"]:
        runs.append({"run": run_no, "time": stamp, "k": res["k"], "embedding_model": svc.settings.embedding_model,
                     "chunk_size": svc.settings.chunk_size_tokens, **row})
    labelled = res["summary"][0]["labelled_cases"]
    msgs = [("ok", f"Run {run_no}: {res['n_cases']} question(s) × {len(strategies)} strategies at k={res['k']}."),
            ("info", res["note"])]
    if labelled < res["n_cases"]:
        msgs.append(("warn", f"{res['n_cases'] - labelled} question(s) have no relevance labels and are excluded from metrics."))
    if any(r["fell_back"] for r in res["summary"]):
        msgs.append(("warn", "Some reranked runs fell back to hybrid because the reranker was unavailable."))
    return (_df(res["summary"]), _df(res["rows"]), _df(runs), runs, res, notices(msgs))


def run_answers(svc: "KnowledgeService", state: Optional[list[dict]], strategy: Optional[str], judge: bool,
                price_in: float, price_out: float, progress: Progress = None
                ) -> tuple[pd.DataFrame, pd.DataFrame, Optional[dict], str]:
    empty = _df([])
    if not state:
        return empty, empty, None, notice("warn", "Add evaluation questions first.")
    try:
        res = run_answer_eval(svc, _cases(state), strategy or None, bool(judge),
                              float(price_in or 0), float(price_out or 0), progress)
    except KnowledgeOSError as e:
        return empty, empty, None, notice("err", safe_user_message(e))
    msgs = [("ok", f"Answered {res['summary']['cases']} question(s).")]
    if not svc.provider_status()["available"]:
        msgs.append(("warn", "No generation provider: answers are evidence-only, so F1, coverage and judge "
                             "scores are blank. Configure a provider in Settings."))
    if judge:
        msgs.append(("info", "LLM-judge scores are model-based opinions, not ground truth."))
    summary = pd.DataFrame([{"metric": k, "value": v} for k, v in res["summary"].items()])
    return summary, _df(res["rows"]), res, notices(msgs)


def export_eval(svc: "KnowledgeService", result: Optional[dict], name: str, fmt: str) -> tuple[Optional[str], str]:
    if not result:
        return None, notice("warn", "Run an evaluation first.")
    content = rows_to_csv(result["rows"]) if fmt == "csv" else results_to_json(result)
    p = svc.export_text(name, content, "csv" if fmt == "csv" else "json")
    return str(p), notice("ok", f"Exported {p.name}.")


def export_cases(svc: "KnowledgeService", state: Optional[list[dict]]) -> tuple[Optional[str], str]:
    if not state:
        return None, notice("warn", "No questions to export.")
    p = svc.export_text("eval_questions", json.dumps(state, indent=2), "json")
    return str(p), notice("ok", f"Exported {p.name} (re-load it later with 'Load file').")


