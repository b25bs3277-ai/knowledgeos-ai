# ============================ diagnostics ============================
def diagnostics(svc: "KnowledgeService") -> tuple[dict[str, Any], str]:
    rep = json.loads(report_json(svc))
    msgs: list[tuple[str, str]] = []
    missing = rep["dependencies"]["missing_required"]
    if missing:
        msgs.append(("err", f"Missing required packages: {', '.join(missing)}. Re-run CELL 01."))
    msgs += [("warn", w) for w in rep["resources"].get("warnings", [])]
    if not rep["index"]["healthy"]:
        msgs.append(("warn", "Index is not consistent; use Document Library → Repair index."))
    if rep["config"]["problems"]:
        msgs.append(("err", "Configuration problems: " + "; ".join(rep["config"]["problems"])))
    if not msgs:
        msgs.append(("ok", "No problems detected."))
    return rep, notices(msgs)


LOG_COLUMNS = ["time", "level", "component", "request id", "message", "details"]


def log_table(level: str = "INFO", limit: int = 200) -> pd.DataFrame:
    rows = []
    for r in reversed(recent_logs(int(limit), level or "INFO")):
        data = r.get("data") or {}
        rows.append([fmt_ts(r.get("ts")), r.get("level"), str(r.get("logger", "")).replace("knowledgeos.", ""),
                     r.get("request_id"), r.get("msg"), json.dumps(data, default=str)[:300] if data else ""])
    return pd.DataFrame(rows, columns=LOG_COLUMNS)


def export_diagnostics(svc: "KnowledgeService") -> tuple[str, str]:
    p = svc.export_text("diagnostics", report_json(svc), "json")
    return str(p), notice("ok", f"Exported {p.name}. It contains no API keys or document text.")


