def settings_values(svc: "KnowledgeService") -> list[Any]:
    return [getattr(svc.settings, f) for f in SETTINGS_FIELDS]


def save_settings(svc: "KnowledgeService", *values: Any) -> str:
    if len(values) != len(SETTINGS_FIELDS):
        return notice("err", "Internal error: settings form is out of sync.")
    changes = {f: v for f, v in zip(SETTINGS_FIELDS, values) if v is not None and v != ""}
    try:
        msgs = svc.update_settings(**changes)
    except ValueError as e:
        return notice("err", f"Not saved: {e}")
    return notices([("warn" if "re-index" in m.lower() else "ok", m) for m in msgs])


def save_api_key(svc: "KnowledgeService", provider: str, key: str) -> str:
    if not (key or "").strip():
        return notice("warn", "Paste a key first (it is kept in memory only and never saved to disk).")
    try:
        return notice("ok", svc.set_api_key(provider, key))
    except KnowledgeOSError as e:
        return notice("err", safe_user_message(e))


def clear_api_key(svc: "KnowledgeService", provider: str) -> str:
    try:
        svc.set_api_key(provider, "")
    except KnowledgeOSError as e:
        return notice("err", safe_user_message(e))
    return notice("ok", f"API key for {provider} removed from memory.")


def provider_summary(svc: "KnowledgeService") -> str:
    p = svc.provider_status()
    keys = ", ".join(f"{k}: {svc.secrets.masked(k)}" for k in ("openai_compatible", "gemini"))
    return (f"**Active provider:** `{p['provider']}`" + (f" · model `{p['model']}`" if p["model"] else "") +
            f"\n\n**Status:** {'✅ ready' if p['available'] else '⚠️ unavailable'} — {p['detail']}"
            f"\n\n**API keys (memory only):** {keys}")


def test_provider(svc: "KnowledgeService") -> str:
    """Send one tiny request. Costs a few tokens on hosted providers."""
    prov = svc.provider
    ok, why = prov.available()
    if not ok:
        return notice("warn", why)
    t0 = time.perf_counter()
    try:
        out = prov.generate([{"role": "user", "content": "Reply with the single word OK."}], 0.0, 8,
                            min(svc.settings.request_timeout_s, 120))
    except KnowledgeOSError as e:
        return notice("err", safe_user_message(e))
    ms = (time.perf_counter() - t0) * 1000
    return notice("ok", f"Provider responded in {ms:.0f} ms: {out.strip()[:60]!r}")


